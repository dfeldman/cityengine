#!/usr/bin/env python3
"""
Writes library.json for tools/sftrees: per SF species, how many models and the ranges each tree's shape may wander
in (the same table Trail Trainer's library.py keeps, trimmed: street trees are all in leaf, no autumn, no winter —
San Francisco's are mostly evergreen, and a city ridden in one season wants one season).

    python3 tools/sftrees/library.py
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent

# species -> models, height range (m), crown-width multiplier range, lean (degrees)
TABLE = {
    'sf_plane':         (10, (10, 17), (0.85, 1.15), (0, 4)),
    'sf_plane_pollard': (6,  (6, 9),   (0.85, 1.15), (0, 3)),
    'sf_ficus':         (8,  (6, 10),  (0.9, 1.15),  (0, 3)),
    'sf_brisbane':      (8,  (7, 13),  (0.85, 1.15), (0, 4)),
    'sf_laurel':        (8,  (5, 10),  (0.85, 1.15), (0, 3)),
    'sf_myrtle':        (6,  (6, 11),  (0.85, 1.15), (0, 6)),
    'sf_olive':         (6,  (4, 8),   (0.85, 1.2),  (0, 8)),
    'sf_bottlebrush':   (4,  (4, 7),   (0.85, 1.2),  (0, 6)),
    'sf_plum':          (5,  (4.5, 8), (0.85, 1.2),  (0, 5)),
    'sf_blossom':       (6,  (4, 7),   (0.85, 1.2),  (0, 6)),
    'sf_pear':          (5,  (5, 9),   (0.85, 1.15), (0, 3)),
    'sf_gum':           (6,  (12, 24), (0.85, 1.2),  (0, 8)),
    'sf_mayten':        (4,  (6, 10),  (0.85, 1.15), (0, 6)),
    'sf_pepper':        (3,  (7, 11),  (0.85, 1.15), (2, 8)),
    'sf_jacaranda':     (4,  (5, 9),   (0.85, 1.2),  (0, 5)),
}


def main() -> None:
    rng = random.Random(1906)
    trees = []
    for species, (n, (lo, hi), width, lean) in TABLE.items():
        for i in range(n):
            h = round(lo + (hi - lo) * (i + rng.random()) / n, 1)   # spread evenly over the range: every size is there
            trees.append({'species': species, 'seed': 5000 + len(trees), 'name': f'{species}_{i + 1:02d}', 'set': [
                f'height=[{h},{round(h * 0.03, 2)}]',
                f'envelope.width_scale={round(rng.uniform(*width), 3)}',
                f'leaves.size_scale={round(rng.uniform(0.92, 1.1), 3)}',
                f'trunk.lean=[{round(rng.uniform(*lean), 1)},2]',
                f'levels.0.angle_offset={round(rng.uniform(-5, 5), 1)}',
                f'leaves.warm={round(rng.random() ** 2 * 0.5, 2)}',
                f'leaves.light_var={round(rng.uniform(0.08, 0.18), 2)}',
            ]})
    (HERE / 'library.json').write_text(json.dumps({'about': 'Generated by library.py; do not edit by hand.', 'total': len(trees), 'trees': trees}, indent=1))
    print(f'{len(trees)} trees')


if __name__ == '__main__':
    main()
