import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=metal', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1400, height: 800 } })
page.on('pageerror', (e) => console.log('pageerror', e.message))
await page.goto(`http://localhost:5200/?city=paris-centre&at=48.8606,2.3376&without=life`)
await page.waitForTimeout(2500)
await page.screenshot({ path: process.argv[2] + '/load.png' })
await page.waitForFunction('window.gameReady === true && window.riderReady === true', null, { timeout: 180_000 })
await page.waitForTimeout(8000)
await page.screenshot({ path: process.argv[2] + '/ui.png' })
await browser.close()
