"""
THE DE YOUNG MUSEUM'S OUTLINES, from OSM (owner, 2026-10-27: "our current version has grass and trees on top … the
grass is supposed to be skylights").

Writes src/render/landmarks/sf/de-young-rings.ts: in city metres (x east, z north, the city's own projection —
src/city/geo.ts, origin 37.793, -122.412):
  - the museum's two outer rings (relation/1652482: the main block way/23867087 and the north-east wing
    way/888799026) and its five courtyards (the inner rings);
  - the Hamon Tower: its foot (way/444230154) and the eight stacked slices OSM draws its twist with
    (way/1418750068…, each with its min_height and height);
  - Three Gems, Turrell's skyspace (way/705001032), the sculpture garden's hedges (way/705001026 …), and the two
    sculptures placed by the model rather than the statue list (Pomodoro's sphere, node/9828842238).

Everything is fetched from the OSM API once and cached in tools/cache/deyoung/.

    python3 tools/deyoung/rings.py
"""
import json, math, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / 'tools/cache/deyoung'
CACHE.mkdir(parents=True, exist_ok=True)

R = 6378137.0
LAT0, LON0 = 37.793, -122.412
KX = math.pi / 180 * R * math.cos(math.radians(LAT0))
KZ = math.pi / 180 * R


def local(lat, lon):
    return (round((lon - LON0) * KX, 2), round((lat - LAT0) * KZ, 2))


def fetch(kind, oid):
    f = CACHE / f'{kind}-{oid}.json'
    if not f.exists():
        url = f'https://api.openstreetmap.org/api/0.6/{kind}/{oid}' + ('/full.json' if kind != 'node' else '.json')
        with urllib.request.urlopen(url, timeout=60) as r:
            f.write_bytes(r.read())
    return json.loads(f.read_text())


def way(oid):
    d = fetch('way', oid)
    nodes = {e['id']: e for e in d['elements'] if e['type'] == 'node'}
    w = next(e for e in d['elements'] if e['type'] == 'way')
    pts = [local(nodes[n]['lat'], nodes[n]['lon']) for n in w['nodes']]
    if len(pts) > 2 and pts[0] == pts[-1]:
        pts = pts[:-1]
    # drop the near-duplicate vertices OSM's mappers leave (a 0.1 m edge makes a sliver wall)
    out = []
    for p in pts:
        if not out or math.hypot(p[0] - out[-1][0], p[1] - out[-1][1]) > 0.4:
            out.append(p)
    if len(out) > 2 and math.hypot(out[0][0] - out[-1][0], out[0][1] - out[-1][1]) < 0.4:
        out.pop()
    return out, w.get('tags', {})


def ccw(r):
    a = sum(r[i][0] * r[(i + 1) % len(r)][1] - r[(i + 1) % len(r)][0] * r[i][1] for i in range(len(r)))
    return r if a > 0 else r[::-1]


def node(oid):
    e = fetch('node', oid)['elements'][0]
    return local(e['lat'], e['lon'])


rel = fetch('relation', 1652482)
members = next(e for e in rel['elements'] if e['type'] == 'relation')['members']
outers = [ccw(way(m['ref'])[0]) for m in members if m['role'] == 'outer']
inners = [ccw(way(m['ref'])[0]) for m in members if m['role'] == 'inner']

foot, _ = way(444230154)
slices = []
for oid in [1418750069, 1418750072, 1418750068, 1418750073, 1418750070, 1418750071, 1418972817, 1418972816]:
    r, t = way(oid)
    slices.append({'ring': ccw(r), 'y0': float(t['min_height']), 'y1': float(t['height'])})
slices.sort(key=lambda s: s['y0'])

gems, _ = way(705001032)
hedges = [way(oid)[0] for oid in (705001026, 705001028, 705001033, 705001035)]

fmt = lambda r: '[' + ','.join(f'[{x},{z}]' for x, z in r) + ']'
lines = [
    '/**',
    ' * The de Young Museum\'s outlines from OSM, in city metres (x east, z north). GENERATED by tools/deyoung/rings.py —',
    ' * edit that, not this. Drawn by de-young.ts.',
    ' */',
    'export type R2 = [number, number][]',
    '/** relation/1652482\'s outer rings (the main block, the north-east wing), anticlockwise */',
    f'export const OUTERS: R2[] = [{",".join(fmt(r) for r in outers)}]',
    '/** its inner rings, the courtyards, anticlockwise */',
    f'export const COURTS: R2[] = [{",".join(fmt(r) for r in inners)}]',
    '/** the Hamon Tower\'s foot (way/444230154) */',
    f'export const TOWER_FOOT: R2 = {fmt(ccw(foot))}',
    '/** its slices, bottom up: each ring between its min_height and height */',
    'export const TOWER: { ring: R2; y0: number; y1: number }[] = [' + ','.join(f'{{ring:{fmt(s["ring"])},y0:{s["y0"]},y1:{s["y1"]}}}' for s in slices) + ']',
    '/** Three Gems (way/705001032): the skyspace\'s mound */',
    f'export const GEMS: R2 = {fmt(ccw(gems))}',
    '/** the sculpture garden\'s hedges (way/705001026, …028, …033, …035), as lines */',
    f'export const GARDEN_HEDGES: R2[] = [{",".join(fmt(r) for r in hedges)}]',
    '/** Pomodoro\'s sphere (node/9828842238) and the Corridor Pin (node/6621511985) */',
    f'export const POMODORO: [number, number] = {list(node(9828842238))}',
    f'export const CORRIDOR_PIN: [number, number] = {list(node(6621511985))}',
    '',
]
out = ROOT / 'src/render/landmarks/sf/de-young-rings.ts'
out.write_text('\n'.join(lines))
print('wrote', out)
cx = sum(p[0] for r in outers for p in r) / sum(len(r) for r in outers)
cz = sum(p[1] for r in outers for p in r) / sum(len(r) for r in outers)
print('outers centroid (city m):', round(cx, 2), round(cz, 2), 'lat/lon', round(LAT0 + cz / KZ, 6), round(LON0 + cx / KX, 6))
print('tower slices:', [(s['y0'], s['y1']) for s in slices])
print('gems centre:', [round(sum(p[i] for p in gems) / len(gems), 2) for i in (0, 1)])
