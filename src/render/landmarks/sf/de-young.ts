/**
 * THE DE YOUNG MUSEUM (Herzog & de Meuron, 2005; relation/1652482) — the MUSEUM in Golden Gate Park, not the de Young
 * Building on Market Street (BUGS.md #147).
 *
 * Rebuilt from OSM's own outlines and the owner's satellite view (2026-10-27: "our current version has grass and trees
 * on top (there are not trees; i think the grass is supposed to be skylights …)"). The first version drew three green
 * "courtyards" on the roof as tree decks, and the city planted them. Read off the satellite view there are two things
 * on that roof, and neither is grass:
 *   - the COURTYARDS: dark wedge-shaped cuts through the whole building, OSM's five inner rings — drawn as voids, glass
 *     walls down to a dark court floor;
 *   - the SKYLIGHTS: pale bands of glass panels running along the long axis, in three rows — drawn flush on the roof.
 * The rest: the dark russet copper over a glazed ground floor set back under it, and the HAMON TOWER from OSM's eight stacked slices (way/
 * 1418750068 …), which carry its twist between them, the glazed observation floor at 46–51 m.
 *
 * And outside, along the south-east front between the building and Hagiwara Tea Garden Drive, the owner's "big bright
 * hedges": rows of clipped hedges in bands of lime, crimson, orange and dark green, run out from the facade
 * (`deYoungHedges`, from the satellite view: OSM does not map them).
 *
 * Every ring is in city metres (de-young-rings.ts, GENERATED by tools/deyoung/rings.py), turned here into the frame
 * the manifest places the model in (public/landmarks/san-francisco/parks.json: 37.771508, −122.468665, rotateDeg
 * 138 — the centre of the box round the main block, wing and tower, its long axis along the main block's).
 */
import earcut from 'earcut'
import type { MeshBuilder } from '../../buildings.ts'
import { capPolygonWithHoles } from '../../buildings.ts'
import type { Fit } from '../fit.ts'
import type { Rgb } from '../../models.ts'
import { surfaceTag } from '../../cartoon-material.ts'
import { offsetRing } from '../parts.ts'
import { COURTS, GARDEN_HEDGES, OUTERS, TOWER, type R2 } from './de-young-rings.ts'

type P2 = { x: number; z: number }

const COPPER: Rgb = [0.30, 0.21, 0.15]
const COPPER_DARK: Rgb = [0.22, 0.16, 0.12]
const ROOF: Rgb = [0.21, 0.19, 0.18]
const GLASS: Rgb = [0.20, 0.24, 0.27]
const SKYLIGHT: Rgb = [0.55, 0.62, 0.66]
const SOFFIT: Rgb = [0.26, 0.19, 0.14]
const COURT_FLOOR: Rgb = [0.22, 0.25, 0.19]
/** the roof, OSM's height */
const H = 13
/** the glazed ground floor, set back under the copper */
const GROUND = 4.4
const SETBACK = 1.4

/** the model's placement, in city metres: the manifest's lat/lon through src/city/geo.ts, and its rotateDeg */
const ANCHOR: [number, number] = [-4984.74, -2392.48]
const ROT = (138 * Math.PI) / 180
const CR = Math.cos(ROT), SR = Math.sin(ROT)
/** a city point (x east, z north) into the model's frame — the inverse of the placement's turn (landmarks.ts groundAt) */
const M = ([x, z]: [number, number]): P2 => {
  const dx = x - ANCHOR[0], dz = z - ANCHOR[1]
  return { x: dx * CR - dz * SR, z: dx * SR + dz * CR }
}
const ring = (r: R2): P2[] => r.map(M)

export function deYoungMuseum(out: MeshBuilder, _fit: Fit): void {
  const copper = surfaceTag('copper')
  const glass = surfaceTag('glass')
  const outers = OUTERS.map(ring)
  const courts = COURTS.map(ring)

  for (const o of outers) {
    const mine = courts.filter((c) => inside(centroid(c), o))
    // the roof, with the courtyards cut through it
    capPolygonWithHoles(out, [o, ...mine.map((c) => [...c].reverse())], H, ROOF, copper)
    // the copper walls from the glazed floor up, on every edge but the one the main block and the wing share
    const shared = (a: P2, b: P2): boolean => outers.some((p) => p !== o && hasVertex(p, a) && hasVertex(p, b))
    walls(out, o, GROUND, H, COPPER, copper, false, shared)
    // the ground floor's glass, set back, and the copper soffit over it
    const back = inset(o, SETBACK)
    walls(out, back, 0, GROUND, GLASS, glass, false, (a, b) => shared(nearest(o, a), nearest(o, b)))
    cap(out, [o, [...back].reverse()], GROUND, false, SOFFIT, copper)
    // the courtyards: glass walls facing into the court, a band of copper under the roof edge, a dark planted floor
    for (const c of mine) {
      walls(out, c, 0, H - 2.2, GLASS, glass, true)
      walls(out, c, H - 2.2, H, COPPER_DARK, copper, true)
      cap(out, [c], 0.55, true, COURT_FLOOR, surfaceTag('concrete'))
    }
  }

  // the skylights: three bands of glass panels along the long axis, where the satellite view shows them pale
  skylights(out, outers, courts)

  // THE HAMON TOWER: OSM's eight slices are its plan stepped every 5 m, from the building's angle at the roof to the
  // street grid at the top; drawn as slices it read as a stack of turned boxes, so the copper is one ruled skin through
  // them — each slice's outline at its middle height, its corners matched to the slice below's — and the glazed
  // observation floor on top under an overhanging copper lid
  const rings = TOWER.map((t) => ring(t.ring))
  for (let k = 1; k < rings.length; k++) {
    const prev = rings[k - 1], r = rings[k]
    let best = 0, bestD = Infinity
    for (let s = 0; s < r.length; s++) {
      const d = prev.reduce((sum, p, j) => sum + Math.hypot(r[(j + s) % r.length].x - p.x, r[(j + s) % r.length].z - p.z), 0)
      if (d < bestD) { bestD = d; best = s }
    }
    rings[k] = prev.map((_, j) => r[(j + best) % r.length])
  }
  const last = TOWER.length - 1
  const ys = TOWER.map((t, k) => (k === 0 ? H : k === last ? t.y0 : (t.y0 + t.y1) / 2))
  for (let k = 0; k < last; k++) {
    const a = rings[k], b = rings[k + 1]
    for (let j = 0; j < a.length; j++) {
      const j1 = (j + 1) % a.length
      const tx = a[j1].x - a[j].x + b[j1].x - b[j].x, tz = a[j1].z - a[j].z + b[j1].z - b[j].z
      const L = Math.hypot(tx, tz)
      out.quad([[a[j].x, ys[k], a[j].z], [a[j1].x, ys[k], a[j1].z], [b[j1].x, ys[k + 1], b[j1].z], [b[j].x, ys[k + 1], b[j].z]],
        [tz / L, 0, -tx / L], [[0, 0], [1, 0], [1, 1], [0, 1]], k % 2 ? COPPER : shadeOf(COPPER, 0.93), copper)
    }
  }
  const t = TOWER[last], r = rings[last]
  walls(out, r, t.y0, t.y1 - 1.0, GLASS, glass)
  const lid = inset(r, -0.8)
  walls(out, lid, t.y1 - 1.0, t.y1, COPPER_DARK, copper)
  cap(out, [lid], t.y1, true, COPPER_DARK, copper)
  cap(out, [lid, [...r].reverse()], t.y1 - 1.0, false, SOFFIT, copper)
  cap(out, [r], t.y1 - 1.0, false, SOFFIT, copper)
}

/**
 * THE HEDGES along the south-east front (owner, 2026-10-27: "there are big bright hedges nearby that should be
 * modeled"): rows of clipped hedges run straight out from the facade, colour by colour — lime, crimson, orange, dark
 * green, gold — the stripes the satellite view shows between the building and Hagiwara Tea Garden Drive: two groups along
 * the main block's face and one along the wing's (from the registered satellite view, as the skylights below), clear of
 * the sphinxes. Which way the rows run is read off the picture, and is the least certain thing here.
 * Placed in the museum's own frame (the manifest gives the hedges the same lat/lon and rotateDeg).
 */
export function deYoungHedges(out: MeshBuilder, fit: Fit): void {
  const leaf = surfaceTag('foliage')
  const COLOURS: Rgb[] = [[0.60, 0.76, 0.16], [0.62, 0.12, 0.15], [0.86, 0.46, 0.12], [0.18, 0.34, 0.15], [0.84, 0.68, 0.18], [0.20, 0.42, 0.16]]
  // the faces, in city metres: the main block's south-east face (way/23867087) and the wing's (way/888799026)
  const faces: { a: [number, number]; b: [number, number]; runs: [number, number][] }[] = [
    { a: [-5017.31, -2473.45], b: [-4949.48, -2412.03], runs: [[12, 32], [66, 89]] },
    { a: [-4941.29, -2404.48], b: [-4910.3, -2376.15], runs: [[14, 40]] },
  ]
  // the two sphinxes by the entrance (public/landmarks/san-francisco-statues.json), which the rows stand clear of
  const SPHINXES = ([[-4952.0, -2424.8], [-4965.0, -2436.8]] as [number, number][]).map(M)
  let k = 0
  for (const f of faces) {
    const a = M(f.a), b = M(f.b)
    const L = Math.hypot(b.x - a.x, b.z - a.z)
    const tx = (b.x - a.x) / L, tz = (b.z - a.z) / L
    // outward from the building: the face runs anticlockwise, so out is to its right
    const nx = tz, nz = -tx
    for (const [u0, u1] of f.runs) {
      for (let u = u0; u <= u1; u += 3.0) {
        const c = COLOURS[k++ % COLOURS.length]
        const h = 1.3 + 0.4 * ((k * 7) % 3) / 2
        // each row from 3 m to 19 m out, in three lengths so the clipped ends step
        for (let s = 0; s < 3; s++) {
          const n0 = 3 + s * 5.4, n1 = n0 + 5.0
          const cx = a.x + tx * u + nx * (n0 + n1) / 2, cz = a.z + tz * u + nz * (n0 + n1) / 2
          if (SPHINXES.some((q) => Math.abs((q.x - cx) * tx + (q.z - cz) * tz) < 2.6 && Math.abs((q.x - cx) * nx + (q.z - cz) * nz) < 5.0)) continue
          const g = fit.groundAt ? fit.groundAt(cx, cz) : 0.5
          hedge(out, cx, cz, g, tx, tz, 0.65, (n1 - n0) / 2, h, c, leaf)
        }
      }
    }
  }
  // the sculpture garden's own hedges, which OSM maps (way/705001026 …): dark, clipped, head height
  for (const line of GARDEN_HEDGES) {
    const r = line.map(M)
    for (let i = 0; i + 1 < r.length; i++) {
      const p = r[i], q = r[i + 1]
      const L = Math.hypot(q.x - p.x, q.z - p.z)
      const steps = Math.max(1, Math.round(L / 6))
      for (let s = 0; s < steps; s++) {
        const m0 = s / steps, m1 = (s + 1) / steps
        const cx = p.x + (q.x - p.x) * (m0 + m1) / 2, cz = p.z + (q.z - p.z) * (m0 + m1) / 2
        const g = fit.groundAt ? fit.groundAt(cx, cz) : 0.5
        hedge(out, cx, cz, g, (q.x - p.x) / L, (q.z - p.z) / L, (L / steps) / 2 + 0.3, 0.6, 1.8, [0.16, 0.30, 0.13], leaf)
      }
    }
  }
}

/** a clipped hedge: a box `hw` across (along t) and `hl` along (along n = (−tz, tx)), a rounded-off top */
function hedge(out: MeshBuilder, cx: number, cz: number, y0: number, tx: number, tz: number, hw: number, hl: number, h: number, c: Rgb, tag: number): void {
  const nx = -tz, nz = tx
  const P = (u: number, v: number, y: number): [number, number, number] => [cx + tx * u + nx * v, y, cz + tz * u + nz * v]
  const sides: [number, number, number, number, [number, number, number]][] = [
    [hw, -hl, hw, hl, [tx, 0, tz]], [-hw, hl, -hw, -hl, [-tx, 0, -tz]], [-hw, -hl, hw, -hl, [-nx, 0, -nz]], [hw, hl, -hw, hl, [nx, 0, nz]],
  ]
  const UV: [number, number][] = [[0, 0], [1, 0], [1, 1], [0, 1]]
  const yb = y0 - 0.3, ye = y0 + h - 0.25
  for (const [u0, v0, u1, v1, n] of sides) out.quad([P(u0, v0, yb), P(u1, v1, yb), P(u1, v1, ye), P(u0, v0, ye)], n, UV, c, tag)
  // the top, chamfered in at the shoulders
  const i = 0.22
  out.quad([P(-hw + i, -hl + i, y0 + h), P(hw - i, -hl + i, y0 + h), P(hw - i, hl - i, y0 + h), P(-hw + i, hl - i, y0 + h)], [0, 1, 0], UV, shadeOf(c, 1.08), tag)
  const top = (a: [number, number], b: [number, number], ai: [number, number], bi: [number, number], n: [number, number, number]): void =>
    out.quad([P(a[0], a[1], ye), P(b[0], b[1], ye), P(bi[0], bi[1], y0 + h), P(ai[0], ai[1], y0 + h)], n, UV, c, tag)
  top([hw, -hl], [hw, hl], [hw - i, -hl + i], [hw - i, hl - i], [tx * 0.7, 0.7, tz * 0.7])
  top([-hw, hl], [-hw, -hl], [-hw + i, hl - i], [-hw + i, -hl + i], [-tx * 0.7, 0.7, -tz * 0.7])
  top([-hw, -hl], [hw, -hl], [-hw + i, -hl + i], [hw - i, -hl + i], [-nx * 0.7, 0.7, -nz * 0.7])
  top([hw, hl], [-hw, hl], [hw - i, hl - i], [-hw + i, hl - i], [nx * 0.7, 0.7, nz * 0.7])
}

/**
 * The skylights, read off the satellite view (owner's, 2026-10-27; registered to OSM by an affine fit on seven points the
 * two share — the café, the pin, Three Gems, Rideout Fountain, Cervantes and two of the building's corners — to 2–6 m) as
 * three bands along the long axis: on the north-west
 * bar, down the middle and along the south-east bar, each about 5 m wide, in panels 4 m long. City metres, each band's
 * two ends; a panel that would land in a courtyard or off the roof is left out.
 */
const BANDS: [[number, number], [number, number]][] = [
  // (this one 9 m in from the north-west face, 20–70 m along it from the west corner: read off the photograph it fell
  //  9 m outside the building, which the satellite view's registration is no better than)
  [[-5047.79, -2410.18], [-5010.59, -2376.78]],
  [[-5007.7, -2411.5], [-4976.8, -2393.4]],
  [[-5004.6, -2446.1], [-4964.6, -2414.1]],
]
function skylights(out: MeshBuilder, outers: P2[][], courts: P2[][]): void {
  const glass = surfaceTag('glass')
  for (const [p, q] of BANDS) {
    const a = M(p), b = M(q)
    const L = Math.hypot(b.x - a.x, b.z - a.z)
    const tx = (b.x - a.x) / L, tz = (b.z - a.z) / L, nx = -tz, nz = tx
    for (let u = 2; u + 4 <= L; u += 5.6) {
      const corners: P2[] = [[u, -2.5], [u + 4, -2.5], [u + 4, 2.5], [u, 2.5]].map(([s, v]) => ({ x: a.x + tx * s + nx * v, z: a.z + tz * s + nz * v }))
      const ok = corners.every((c) => outers.some((o) => inside(c, o)) && !courts.some((k) => near(c, k, 1.5)))
      if (!ok) continue
      out.quad(corners.map((c) => [c.x, H + 0.06, c.z] as [number, number, number]), [0, 1, 0], [[0, 0], [1, 0], [1, 1], [0, 1]], SKYLIGHT, glass)
    }
  }
}

/** walls on every edge of a ring between y0 and y1, facing out of it (an anticlockwise ring) or into it (`into`) */
function walls(out: MeshBuilder, r: P2[], y0: number, y1: number, c: Rgb, tag: number, into = false, skip?: (a: P2, b: P2) => boolean): void {
  for (let i = 0; i < r.length; i++) {
    const a = r[i], b = r[(i + 1) % r.length]
    if (skip?.(a, b)) continue
    const L = Math.hypot(b.x - a.x, b.z - a.z)
    if (L < 0.05) continue
    const tx = (b.x - a.x) / L, tz = (b.z - a.z) / L
    const s = into ? -1 : 1
    out.quad([[a.x, y0, a.z], [b.x, y0, b.z], [b.x, y1, b.z], [a.x, y1, a.z]], [s * tz, 0, -s * tx], [[0, 0], [L / 3, 0], [L / 3, (y1 - y0) / 3], [0, (y1 - y0) / 3]], c, tag)
  }
}

/** a flat polygon (the first ring the outline, the rest holes) at y, facing up or down */
function cap(out: MeshBuilder, rings: P2[][], y: number, up: boolean, c: Rgb, tag: number): void {
  const flat: number[] = [], holes: number[] = [], all: P2[] = []
  rings.forEach((r, i) => { if (i > 0) holes.push(all.length); for (const p of r) { flat.push(p.x, p.z); all.push(p) } })
  const tris = earcut(flat, holes)
  const base = out.positions.length / 3
  for (const p of all) {
    out.positions.push(p.x, y, p.z)
    out.normals.push(0, up ? 1 : -1, 0)
    out.uvs.push(p.x / 3, p.z / 3)
    out.colors.push(c[0], c[1], c[2], tag)
  }
  for (let i = 0; i < tris.length; i += 3) {
    const a = all[tris[i]], b = all[tris[i + 1]], d = all[tris[i + 2]]
    // the y of (b − a) × (d − a); negative is the side drawn (buildings.ts pushUpward)
    const ny = (b.z - a.z) * (d.x - a.x) - (b.x - a.x) * (d.z - a.z)
    if ((ny <= 0) === up) out.indices.push(base + tris[i], base + tris[i + 1], base + tris[i + 2])
    else out.indices.push(base + tris[i], base + tris[i + 2], base + tris[i + 1])
  }
}

/** an anticlockwise ring moved `d` inward (negative: outward), whichever way offsetRing counts */
function inset(r: P2[], d: number): P2[] {
  return offsetRing(r, area(r) > 0 ? -d : d)
}
const area = (r: P2[]): number => {
  let a = 0
  for (let i = 0; i < r.length; i++) { const j = (i + 1) % r.length; a += r[i].x * r[j].z - r[j].x * r[i].z }
  return a / 2
}
const centroid = (r: P2[]): P2 => ({ x: r.reduce((s, p) => s + p.x, 0) / r.length, z: r.reduce((s, p) => s + p.z, 0) / r.length })
const hasVertex = (r: P2[], p: P2): boolean => r.some((q) => Math.hypot(q.x - p.x, q.z - p.z) < 0.05)
const nearest = (r: P2[], p: P2): P2 => r.reduce((best, q) => (Math.hypot(q.x - p.x, q.z - p.z) < Math.hypot(best.x - p.x, best.z - p.z) ? q : best))
const shadeOf = (c: Rgb, f: number): Rgb => [Math.min(1, c[0] * f), Math.min(1, c[1] * f), Math.min(1, c[2] * f)]
function inside(p: P2, r: P2[]): boolean {
  let hit = false
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    if ((r[i].z > p.z) !== (r[j].z > p.z) && p.x < ((r[j].x - r[i].x) * (p.z - r[i].z)) / (r[j].z - r[i].z) + r[i].x) hit = !hit
  }
  return hit
}
/** inside the ring, or within `d` of one of its edges */
function near(p: P2, r: P2[], d: number): boolean {
  if (inside(p, r)) return true
  for (let i = 0; i < r.length; i++) {
    const a = r[i], b = r[(i + 1) % r.length]
    const L2 = (b.x - a.x) ** 2 + (b.z - a.z) ** 2
    const t = L2 ? Math.max(0, Math.min(1, ((p.x - a.x) * (b.x - a.x) + (p.z - a.z) * (b.z - a.z)) / L2)) : 0
    if (Math.hypot(p.x - a.x - t * (b.x - a.x), p.z - a.z - t * (b.z - a.z)) < d) return true
  }
  return false
}

