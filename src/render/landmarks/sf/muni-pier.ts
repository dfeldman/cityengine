const CONCRETE: Rgb = [0.74, 0.72, 0.67]
const DECK: Rgb = [0.66, 0.64, 0.6]
const PILE: Rgb = [0.5, 0.49, 0.46]
const IRON: Rgb = [0.16, 0.17, 0.18]

export function municipalPier(out: MeshBuilder): void {
  const ring = RING_LL.map(([lat, lon]) => ({ x: (lon - ANCHOR.lon) * KX, z: (lat - ANCHOR.lat) * KZ }))
  const TOP = 0.35, SLAB = 0.9, DOWN = -9
  capPolygon(out, ring, TOP, DECK, FIXED)
  const n = ring.length
  let run = 0
  // (the closing edge, n-1 → 0, is the shore end: no parapet across it, only the gate)
  for (let i = 0; i < n - 1; i++) {
    const a = ring[i], b = ring[i + 1]
    const L = Math.hypot(b.x - a.x, b.z - a.z)
    if (L < 0.05) continue
    const ux = (b.x - a.x) / L, uz = (b.z - a.z) / L
    // outward normal of an anticlockwise ring: to the right of the direction of travel
    const nx = uz, nz = -ux
    // the slab's edge, and the parapet on it (set in 0.15 m so it stands on the deck)
    out.quad([[a.x, TOP, a.z], [b.x, TOP, b.z], [b.x, TOP - SLAB, b.z], [a.x, TOP - SLAB, a.z]], [nx, 0, nz],
      [[0, 0], [L, 0], [L, SLAB], [0, SLAB]], CONCRETE, FIXED)
    const ix = -nx * 0.15, iz = -nz * 0.15
    strut(out, [a.x + ix, TOP + 0.5, a.z + iz], [b.x + ix, TOP + 0.5, b.z + iz], 0.25, 1.0, CONCRETE, FIXED)
    strut(out, [a.x + ix, TOP + 1.03, a.z + iz], [b.x + ix, TOP + 1.03, b.z + iz], 0.34, 0.08, [0.8, 0.78, 0.73], FIXED)
    // piles under the edge every 6 m, and lamp standards every 30 m
    for (let s = (6 - (run % 6)) % 6; s < L; s += 6) {
      const x = a.x + ux * s - nx * 0.6, z = a.z + uz * s - nz * 0.6
      prism(out, x, z, DOWN, TOP - SLAB, 0.32, 8, PILE, FIXED)
      if (Math.round((run + s) / 6) % 5 === 0) {
        const lx = a.x + ux * s - nx * 0.45, lz = a.z + uz * s - nz * 0.45
        prism(out, lx, lz, TOP, TOP + 5.2, 0.09, 8, IRON, FIXED, 0.06)
        strut(out, [lx, TOP + 5.1, lz], [lx - nx * 0.6, TOP + 5.1, lz - nz * 0.6], 0.06, 0.06, IRON, FIXED)
        box(out, lx - nx * 0.6, TOP + 4.95, lz - nz * 0.6, 0.16, 0.12, 0.16, [1.0, 0.93, 0.72], EMIT)
      }
    }
    run += L
  }
  // a locked gate across the shore end (closed since 2022): two posts and a chain-link panel
  const g0 = ring[0], g1 = ring[n - 1]
  for (const p of [g0, g1]) prism(out, p.x, p.z, TOP, TOP + 2.2, 0.08, 8, IRON, FIXED)
  strut(out, [g0.x, TOP + 1.1, g0.z], [g1.x, TOP + 1.1, g1.z], 0.05, 2.1, [0.55, 0.57, 0.58], FIXED)
}
