/**
 * THE JAPANESE TEA GARDEN'S LANDSCAPE: its hero plants, rocks and water (owner, 2026-10-25: "work on the Japanese garden
 * plants, rocks, and water features. Do not attempt sculptures or buildings or other constructed objects yet").
 * The ground, the ponds and the general planting are the bake's (docs/TEA-GARDEN.md); this draws what a zone cannot:
 *
 *  - CLOUD-PRUNED PINES (niwaki): a leaning, curving trunk carrying flat pads of foliage at the ends of its branches,
 *    as the one before the Temple Gate (holymtn.com garden photographs);
 *  - the MT FUJI HEDGE (1979, for Makoto Hagiwara): a broad clipped cone with a flat-topped cap, before a bamboo
 *    screen, stones at its foot on the moss; the DRAGON HEDGE: a long clipped hedge humped like a dragon's back;
 *  - the DWARF TREES on Waterfall Hill (Hoodline, 2017: the Hagiwara family's), and the WATERFALL coming down that
 *    hill — the pagoda terrace's slope, 2.6 m in 7 m in the lidar — in three ledges into the Main Pond's north arm;
 *  - clipped AZALEA DOMES (tamamono) and ROCKS round the ponds' edges, REEDS at their quiet ends, and the STREAM that
 *    joins the drum bridge pond to the Main Pond.
 *
 * Every position is in tea-garden-layout.ts (generated by tools/teagarden/layout.py, kept off the paths and out of the
 * buildings). Standalone entry at the garden's middle, NOT draped: each piece stands on the ground under it
 * (`fit.groundAt`). Local frame x east, z north (front 180), city metres about MID as tea-garden.ts's grounds.
 */
import type { MeshBuilder } from '../../buildings.ts'
import type { Fit } from '../fit.ts'
import { prism, strut, type Rgb } from '../../models.ts'
import { surfaceTag } from '../../cartoon-material.ts'
import { BAMBOO, DOMES, DRAGON, DWARF, DWARF_PINES, FALL, FUJI, FUJI_ROCKS, PINES, POND_ROCKS, REEDS, STREAM } from './tea-garden-layout.ts'

const MID = { x: -5110, z: -2530 }
const L = (x: number, z: number): [number, number] => [x - MID.x, z - MID.z]

const h1 = (a: number, b: number): number => { const v = Math.sin(a * 127.1 + b * 311.7) * 43758.5453; return v - Math.floor(v) }
const shade = (c: Rgb, k: number): Rgb => [c[0] * k, c[1] * k, c[2] * k]

// (the greens set dark: the flat material lights them about 1.6 times — the Mt Fuji hedge at 0.36/0.48 came out lime)
const PINE: Rgb = [0.08, 0.16, 0.07]
const TRUNK: Rgb = [0.3, 0.22, 0.16]
const CLIPPED: Rgb = [0.13, 0.22, 0.08]
const FUJI_GREEN: Rgb = [0.12, 0.19, 0.06]
const DRAGON_GREEN: Rgb = [0.1, 0.19, 0.08]
const CULM: Rgb = [0.27, 0.34, 0.15]
const BAMBOO_LEAF: Rgb = [0.13, 0.23, 0.08]
const WATER: Rgb = [0.13, 0.2, 0.22]
const FOAM: Rgb = [0.9, 0.94, 0.95]
const AZALEA: Record<string, Rgb> = { green: CLIPPED, pink: [0.86, 0.46, 0.6], magenta: [0.74, 0.22, 0.48], red: [0.78, 0.2, 0.2] }
// (dark: the rock material lightens them a good deal — at 0.42 they read cream)
const ROCKS: Rgb[] = [[0.26, 0.25, 0.23], [0.22, 0.22, 0.2], [0.29, 0.28, 0.25], [0.2, 0.22, 0.18]]

type V3 = [number, number, number]
const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
const UV: [number, number][] = [[0, 0], [1, 0], [1, 1], [0, 1]]

/**
 * A lump: an ellipsoid (or its upper half) with its radius jittered per vertex — a rock with `noise` 0.3, a clipped
 * shrub or a pine's pad with 0.06. Flat-shaded quads; the poles collapse to points.
 */
function lump(out: MeshBuilder, cx: number, cy: number, cz: number, rx: number, ry: number, rz: number, seed: number,
  c: Rgb, tag: number, noise: number, segs = 8, rings = 4, half = false): void {
  const v: V3[][] = []
  for (let i = 0; i <= rings; i++) {
    const lat = half ? (i / rings) * (Math.PI / 2) : -Math.PI / 2 + (i / rings) * Math.PI
    const row: V3[] = []
    for (let j = 0; j < segs; j++) {
      const lon = (j / segs) * Math.PI * 2
      const pole = i === rings || (!half && i === 0)
      const k = pole ? 1 : 1 + noise * (h1(seed + i * 13.1, j * 7.7) - 0.5) * 2
      row.push([cx + Math.cos(lat) * Math.cos(lon) * rx * k, cy + Math.sin(lat) * ry * (pole ? 1 : 1 + noise * 0.5 * (h1(seed + j, i) - 0.5)), cz + Math.cos(lat) * Math.sin(lon) * rz * k])
    }
    v.push(row)
  }
  for (let i = 0; i < rings; i++) {
    for (let j = 0; j < segs; j++) {
      const a = v[i][j], b = v[i][(j + 1) % segs], d = v[i + 1][j], e = v[i + 1][(j + 1) % segs]
      let n = cross(sub(e, a), sub(d, b))
      const m: V3 = [(a[0] + e[0]) / 2 - cx, (a[1] + e[1]) / 2 - cy, (a[2] + e[2]) / 2 - cz]
      if (n[0] * m[0] + n[1] * m[1] + n[2] * m[2] < 0) n = [-n[0], -n[1], -n[2]]
      const len = Math.hypot(n[0], n[1], n[2]) || 1
      // (the underside a little darker, the top a little lighter: it reads as a mass in flat light)
      const k = 0.82 + 0.3 * (i / rings) + 0.08 * (h1(seed, i * segs + j) - 0.5)
      out.quad([a, b, e, d], [n[0] / len, n[1] / len, n[2] / len], UV, shade(c, k), tag)
    }
  }
}

/** a cloud-pruned pine: a trunk curving away towards `lean`, branches ending in flat pads, a pad at the top */
function niwaki(out: MeshBuilder, x: number, z: number, y: number, h: number, lean: number, seed: number): void {
  const lx = Math.sin((lean * Math.PI) / 180), lz = Math.cos((lean * Math.PI) / 180)
  const s = h / 4.5
  const P = (t: number): V3 => {
    const off = 0.32 * h * Math.pow(t, 1.25) + 0.35 * s * Math.sin(t * 5 + seed)
    const side = 0.25 * s * Math.sin(t * 7 + seed * 0.3)
    return [x + lx * off - lz * side, y + t * h * 0.92, z + lz * off + lx * side]
  }
  const N = 6
  for (let i = 0; i < N; i++) {
    const a = P(i / N), b = P((i + 1) / N)
    const w = (0.34 - 0.2 * (i / N)) * s
    strut(out, a, b, w, w, TRUNK)
  }
  // the pads: low on the trunk the widest, reaching out; each on a short branch
  const tiers = h > 2.6 ? [0.42, 0.56, 0.7, 0.83] : [0.55, 0.78]
  tiers.forEach((t, k) => {
    const base = P(t)
    const ang = seed * 0.7 + k * 2.3 + (k % 2) * Math.PI * 0.8
    const reach = (1.5 - t) * 1.25 * s
    const tip: V3 = [base[0] + Math.sin(ang) * reach, base[1] + 0.25 * s, base[2] + Math.cos(ang) * reach]
    strut(out, base, tip, 0.1 * s, 0.1 * s, TRUNK)
    const r = (1.25 - t * 0.6) * s
    lump(out, tip[0], tip[1] + 0.12 * s, tip[2], r, 0.3 * s, r * (0.8 + 0.3 * h1(seed, k)), seed + k * 31, PINE, 0, 0.12, 9, 4)
  })
  const top = P(1)
  lump(out, top[0], top[1] + 0.1 * s, top[2], 0.85 * s, 0.42 * s, 0.75 * s, seed + 97, PINE, 0, 0.12, 9, 4)
}

export function teaGardenLandscape(out: MeshBuilder, fit: Fit): void {
  const g = (x: number, z: number): number => fit.groundAt?.(x, z) ?? 0
  const ROCK = surfaceTag('rock')
  const rock = (x: number, z: number, r: number, hh: number, seed: number, sink = 0.35): void => {
    lump(out, x, g(x, z) - hh * sink, z, r, hh, r * (0.7 + 0.5 * h1(seed, 1)), seed, ROCKS[seed % ROCKS.length], ROCK, 0.3, 7, 4)
  }

  // ---- the cloud-pruned pines, and the little ones on Waterfall Hill
  for (const [cx, cz, hh, lean, seed] of [...PINES, ...DWARF_PINES]) {
    const [x, z] = L(cx, cz)
    niwaki(out, x, z, g(x, z) - 0.1, hh, lean, seed % 1000)
  }
  // ---- the dwarf trees from the plant library: mugo pines, junipers, heather
  for (const [cx, cz, species, hh] of DWARF) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species, h: hh, spin: h1(cx, cz) * Math.PI * 2 })
  }
  // ---- clipped azalea domes behind the waterline, some in flower
  for (const [cx, cz, r, hh, c] of DOMES) {
    const [x, z] = L(cx, cz)
    lump(out, x, g(x, z) - 0.12, z, r, hh, r * (0.85 + 0.25 * h1(cx, cz)), Math.round(cx * 7 + cz), AZALEA[c] ?? CLIPPED, 0, 0.06, 8, 3, true)
  }
  // ---- rocks at the waterline
  for (const [cx, cz, r, hh, seed] of POND_ROCKS) rock(...L(cx, cz), r, hh, seed)
  // ---- reeds and cattails
  for (const [cx, cz, species, hh] of REEDS) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species, h: hh, spin: h1(cz, cx) * Math.PI * 2 })
  }

  // ---- the Mt Fuji hedge: a broad clipped cone, a flat-topped cap; stones before it on the moss
  {
    const [x, z] = L(...FUJI)
    const y = g(x, z) - 0.35
    prism(out, x, z, y, y + 2.55, 2.9, 18, FUJI_GREEN, 0, 1.05)
    prism(out, x, z, y + 2.55, y + 2.95, 1.05, 18, shade(FUJI_GREEN, 1.12), 0, 0.6)
    for (const [cx, cz, r, hh, seed] of FUJI_ROCKS) rock(...L(cx, cz), r, hh, seed, 0.3)
  }
  // ---- the Dragon Hedge: clipped mounds along a line that winds twice, humped, the head end raised
  {
    const [ax, az] = L(...DRAGON[0]), [bx, bz] = L(...DRAGON[1])
    const len = Math.hypot(bx - ax, bz - az), nx = -(bz - az) / len, nz = (bx - ax) / len
    const n = Math.round(len / 0.55)
    for (let i = 0; i <= n; i++) {
      const t = i / n
      const w = Math.sin(t * Math.PI * 4) * 0.8
      const x = ax + (bx - ax) * t + nx * w, z = az + (bz - az) * t + nz * w
      const hh = 0.85 + 0.45 * Math.abs(Math.sin(t * Math.PI * 3)) + (t > 0.88 ? (t - 0.88) * 7 : 0)
      lump(out, x, g(x, z) - 0.1, z, 0.62, hh, 0.62, i * 17, DRAGON_GREEN, 0, 0.05, 8, 3, true)
    }
  }
  // ---- bamboo: thin pale culms, leaf clouds on their upper half
  for (const [cx, cz, hh, seed] of BAMBOO) {
    const [x, z] = L(cx, cz)
    const y = g(x, z)
    const tx = (h1(seed, 2) - 0.5) * 0.5, tz = (h1(seed, 3) - 0.5) * 0.5
    strut(out, [x, y, z], [x + tx, y + hh, z + tz], 0.05, 0.05, CULM)
    // (the leaves: a ragged cloud on every other culm, big enough to run together into the grove's canopy — a cloud on
    //  each culm read as lollipops, small flat ones as umbrellas)
    if (seed % 2 === 0) {
      const a = seed * 0.37
      lump(out, x + tx * 0.7 + Math.sin(a) * 0.3, y + hh * 0.66, z + tz * 0.7 + Math.cos(a) * 0.3, 1.3, 1.6, 1.2, seed, BAMBOO_LEAF, 0, 0.22, 8, 4)
    }
  }

  // ---- the waterfall: three ledges cut into the slope, each a still pool ending in a white drop, rocks along both
  // banks and at every lip, foam where it meets the pond
  {
    const [tx, tz] = L(...FALL.top), [fx, fz] = L(...FALL.foot)
    const len = Math.hypot(fx - tx, fz - tz), ux = (fx - tx) / len, uz = (fz - tz) / len, nx = -uz, nz = ux
    const at = (t: number, side: number): [number, number] => [tx + ux * len * t + nx * side, tz + uz * len * t + nz * side]
    const W = 0.55
    const cuts = [0, 0.32, 0.62, 0.86, 1]
    // each ledge's water is level with the ground at its own downstream end, a little over it
    const level = cuts.map((t) => g(...at(Math.min(1, t), 0)) + 0.08)
    for (let k = 0; k < 4; k++) {
      const t0 = cuts[k], t1 = cuts[k + 1], y = level[k + 1]
      const p0 = at(t0, -W), p1 = at(t1, -W), p2 = at(t1, W), p3 = at(t0, W)
      out.quad([[p0[0], y, p0[1]], [p1[0], y, p1[1]], [p2[0], y, p2[1]], [p3[0], y, p3[1]]], [0, 1, 0], UV, WATER, 0)
      // the drop off this ledge's lip, down to the next
      if (k < 3) {
        const yb = level[k + 2]
        const a = at(t1, -W * 0.8), b = at(t1, W * 0.8)
        out.quad([[a[0], y, a[1]], [b[0], y, b[1]], [b[0], yb, b[1]], [a[0], yb, a[1]]], [ux, 0, uz], UV, FOAM, 0)
        for (const sd of [-1, 1]) {
          const [rx, rz] = at(t1, sd * (W + 0.35))
          lump(out, rx, y - 0.15, rz, 0.55, 0.5, 0.5, k * 7 + (sd > 0 ? 3 : 0), ROCKS[(k + 1) % 4], ROCK, 0.3, 7, 4)
        }
      }
    }
    // the banks: rocks the length of it, larger at the top
    for (let i = 0; i <= 9; i++) {
      const t = i / 9
      for (const sd of [-1, 1]) {
        const [rx, rz] = at(t, sd * (W + 0.55 + 0.3 * h1(i, sd)))
        const r = 0.75 - 0.35 * t + 0.2 * h1(sd, i)
        rock(rx, rz, r, r * 0.8, 400 + i * 2 + (sd > 0 ? 1 : 0), 0.3)
      }
    }
    // the spring: a heap of stones at the top; the foam at the foot
    for (let k = 0; k < 3; k++) {
      const [rx, rz] = at(-0.08, (k - 1) * 0.9)
      rock(rx, rz, 0.8, 0.75, 450 + k, 0.25)
    }
    const [ex, ez] = at(1.05, 0)
    lump(out, ex, level[4] - 0.05, ez, 1.1, 0.12, 0.9, 77, FOAM, 0, 0.1, 9, 2, true)
  }

  // ---- the stream between the drum bridge pond and the Main Pond: a ribbon of water a little over the ground,
  // stepping down to the Main Pond, small stones along it
  {
    const [ax, az] = L(...STREAM[0]), [bx, bz] = L(...STREAM[1])
    const len = Math.hypot(bx - ax, bz - az), nx = -(bz - az) / len, nz = (bx - ax) / len
    const n = Math.max(2, Math.round(len / 0.8))
    let prev = Infinity
    const pts: { x: number; z: number; y: number }[] = []
    for (let i = 0; i <= n; i++) {
      const t = i / n, x = ax + (bx - ax) * t, z = az + (bz - az) * t
      const y = Math.min(prev, g(x, z) + 0.06)
      prev = y
      pts.push({ x, z, y })
    }
    const W = 0.7
    for (let i = 0; i < n; i++) {
      const a = pts[i], b = pts[i + 1]
      out.quad([[a.x - nx * W, a.y, a.z - nz * W], [b.x - nx * W, b.y, b.z - nz * W], [b.x + nx * W, b.y, b.z + nz * W], [a.x + nx * W, a.y, a.z + nz * W]], [0, 1, 0], UV, WATER, 0)
      for (const sd of [-1, 1]) if (h1(i, sd) < 0.6) rock(a.x + nx * sd * (W + 0.25), a.z + nz * sd * (W + 0.25), 0.3 + 0.2 * h1(sd, i), 0.25, 500 + i * 2 + (sd > 0 ? 1 : 0), 0.4)
    }
  }
}
