/**
 * THE JAPANESE TEA GARDEN'S LANDSCAPE: its hero plants, rocks and water (owner, 2026-10-25: "work on the Japanese garden
 * plants, rocks, and water features. Do not attempt sculptures or buildings or other constructed objects yet"; 2026-10-26:
 * "as beautiful and accurate as possible using the required number of polys or fewer … prioritize plants, rocks and
 * water since we can use photogrammetry for buildings and statues").
 * The ground, the ponds and the general planting are the bake's (docs/TEA-GARDEN.md); this draws what a zone cannot:
 *
 *  - CLOUD-PRUNED PINES (niwaki), as the one before the Temple Gate (holymtn.com garden photographs): the plant
 *    library's `niwaki` since 2026-10-26 (assetkit bushgen), placed where the layout puts them;
 *  - the MT FUJI HEDGE (1979, for Makoto Hagiwara): a broad clipped cone with a flat-topped cap, before a bamboo
 *    screen, stones at its foot on the moss; the DRAGON HEDGE on the path to Maple Lane and the NEW DRAGON HEDGE beside
 *    Mt Fuji: long clipped hedges humped like a dragon's back, bamboo behind;
 *  - the DWARF TREES on Waterfall Hill (Hoodline, 2017: the Hagiwara family's), and the WATERFALL coming down that
 *    hill — the pagoda terrace's slope, 2.6 m in 7 m in the lidar — in three ledges into the Main Pond's north arm;
 *    the TEA HOUSE'S WATERFALL off its terrace into its pond (the garden's map: "set beside a waterfall and pond");
 *  - the ISLANDS: the Main Pond's (a stone pagoda stands on it — the owner's GLB) and the tea house pond's
 *    tortoise-shaped Horai-jima, each a mossy mound ringed with stones and a little pine;
 *  - clipped AZALEA DOMES (tamamono) and ROCKS round the ponds' edges, ROCK GROUPS (ishigumi: three stones, one
 *    standing) at the Buddha, the drum bridge pool, the Temple Gate; REEDS and LILY PADS at the ponds' quiet ends,
 *    and the STREAM that joins the drum bridge pond to the Main Pond.
 *
 * What the PLANT LIBRARY draws instead (MeshBuilder.plants → render/plants.ts, instanced, nothing against this builder's
 * 25,000-triangle ceiling): the bamboo groves (`bamboo`), the massed azaleas (`azalea`: in pink, rose, blush or green),
 * the irises on the path to the drum bridge (`japanese_iris`), the sword ferns (`fern`, `bracken`), the dwarf mugo pines
 * and junipers, the reeds and cattails. The three new species are assetkit's plantgen (2026-10-26), in its library table
 * `library-teagarden.json`.
 *
 * Every position is in tea-garden-layout.ts (generated by tools/teagarden/layout.py, kept off the paths and out of the
 * buildings). Standalone entry at the garden's middle, NOT draped: each piece stands on the ground under it
 * (`fit.groundAt`). A pond's WATER LEVEL is its lowest bank, the bake's own rule (city/package.ts waterLevels), read
 * off the same ground here, so the islands and the lily pads sit on the water. Local frame x east, z north (front 180),
 * city metres about MID as tea-garden.ts's grounds.
 */
import type { MeshBuilder } from '../../buildings.ts'
import type { Fit } from '../fit.ts'
import { prism, type Rgb } from '../../models.ts'
import { surfaceTag } from '../../cartoon-material.ts'
import { AZALEAS, BAMBOO, DOMES, DRAGON, DRAGON2, DWARF, DWARF_PINES, FALL, FALL2, FERNS, FUJI, FUJI_ROCKS, IRIS, ISLANDS, PADS, PINES, PONDS, POND_ROCKS, REEDS, ROCK_GROUPS, STREAM } from './tea-garden-layout.ts'

const MID = { x: -5110, z: -2530 }
const L = (x: number, z: number): [number, number] => [x - MID.x, z - MID.z]

const h1 = (a: number, b: number): number => { const v = Math.sin(a * 127.1 + b * 311.7) * 43758.5453; return v - Math.floor(v) }
const shade = (c: Rgb, k: number): Rgb => [c[0] * k, c[1] * k, c[2] * k]

// (the greens set dark: the flat material lights them about 1.6 times — the Mt Fuji hedge at 0.36/0.48 came out lime)
const CLIPPED: Rgb = [0.17, 0.27, 0.1]
const FUJI_GREEN: Rgb = [0.12, 0.19, 0.06]
const DRAGON_GREEN: Rgb = [0.15, 0.26, 0.1]
const MOSS: Rgb = [0.13, 0.23, 0.07]
const PAD: Rgb = [0.07, 0.16, 0.05]
const WATER: Rgb = [0.13, 0.2, 0.22]
const FOAM: Rgb = [0.9, 0.94, 0.95]
// (dark: the rock material lightens them a good deal — at 0.42 they read cream)
const ROCKS: Rgb[] = [[0.26, 0.25, 0.23], [0.22, 0.22, 0.2], [0.29, 0.28, 0.25], [0.2, 0.22, 0.18]]

type V3 = [number, number, number]
const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
const UV: [number, number][] = [[0, 0], [1, 0], [1, 1], [0, 1]]

/**
 * A lump: an ellipsoid (or its upper half) with its radius jittered per vertex — a rock with `noise` 0.35, a clipped
 * shrub or a pine's pad with 0.06. Flat-shaded quads; the poles collapse to points. `squash` flattens its top (a
 * clipped dome, a pine's pad: the mass is in the shoulders, not a sphere's crown).
 */
function lump(out: MeshBuilder, cx: number, cy: number, cz: number, rx: number, ry: number, rz: number, seed: number,
  c: Rgb, tag: number, noise: number, segs = 8, rings = 4, half = false, squash = 0): void {
  const v: V3[][] = []
  for (let i = 0; i <= rings; i++) {
    const lat = half ? (i / rings) * (Math.PI / 2) : -Math.PI / 2 + (i / rings) * Math.PI
    const row: V3[] = []
    for (let j = 0; j < segs; j++) {
      const lon = (j / segs) * Math.PI * 2
      const pole = i === rings || (!half && i === 0)
      const k = pole ? 1 : 1 + noise * (h1(seed + i * 13.1, j * 7.7) - 0.5) * 2
      const sy = Math.sin(lat) > 0 ? Math.sin(lat) * (1 - squash) + squash * Math.pow(Math.sin(lat), 0.4) : Math.sin(lat)
      const ck = pole ? 1 : 1 + noise * 0.5 * (h1(seed + j, i) - 0.5)
      row.push([cx + Math.cos(lat) * Math.cos(lon) * rx * k, cy + sy * ry * ck, cz + Math.cos(lat) * Math.sin(lon) * rz * k])
    }
    v.push(row)
  }
  for (let i = 0; i < rings; i++) {
    for (let j = 0; j < segs; j++) {
      const a = v[i][j], b = v[i][(j + 1) % segs], d = v[i + 1][j], e = v[i + 1][(j + 1) % segs]
      let n = cross(sub(e, a), sub(d, b))
      const m: V3 = [(a[0] + e[0]) / 2 - cx, (a[1] + e[1]) / 2 - cy, (a[2] + e[2]) / 2 - cz]
      if (n[0] * m[0] + n[1] * m[1] + n[2] * m[2] < 0) n = [-n[0], -n[1], -n[2]]
      const len = Math.hypot(n[0], n[1], n[2]) || 1
      // (the underside a little darker, the top a little lighter: it reads as a mass in flat light)
      const k = 0.82 + 0.3 * (i / rings) + 0.08 * (h1(seed, i * segs + j) - 0.5)
      out.quad([a, b, e, d], [n[0] / len, n[1] / len, n[2] / len], UV, shade(c, k), tag)
    }
  }
}

export function teaGardenLandscape(out: MeshBuilder, fit: Fit): void {
  const g = (x: number, z: number): number => fit.groundAt?.(x, z) ?? 0
  const ROCK = surfaceTag('rock')
  // a stone: a faceted lump, strongly jittered, bedded into the ground — angular, as the garden's set stones are
  const rock = (x: number, z: number, r: number, hh: number, seed: number, sink = 0.35, y?: number): void => {
    lump(out, x, (y ?? g(x, z)) - hh * sink, z, r, hh, r * (0.7 + 0.5 * h1(seed, 1)), seed, ROCKS[seed % ROCKS.length], ROCK, 0.36, 6, 3)
  }
  // a standing stone (tate-ishi): tall, narrow, leaning a little, its foot buried
  const standing = (x: number, z: number, hh: number, bearing: number, seed: number): void => {
    const y = g(x, z)
    const tilt = 0.12 * hh
    lump(out, x + Math.sin(bearing) * tilt * 0.5, y + hh * 0.3, z + Math.cos(bearing) * tilt * 0.5, hh * 0.32, hh * 0.62, hh * 0.22, seed, ROCKS[(seed + 1) % ROCKS.length], ROCK, 0.3, 6, 3)
  }
  // a rock group (ishigumi): one standing stone, two lower companions, a small one at the foot
  const rockGroup = (x: number, z: number, bearingDeg: number, scale: number, seed: number): void => {
    const b = (bearingDeg * Math.PI) / 180, ux = Math.sin(b), uz = Math.cos(b), nx = -uz, nz = ux
    standing(x, z, 1.35 * scale, b, seed)
    rock(x + ux * 0.9 * scale + nx * 0.5 * scale, z + uz * 0.9 * scale + nz * 0.5 * scale, 0.55 * scale, 0.42 * scale, seed + 1, 0.3)
    rock(x - ux * 0.5 * scale + nx * 1.0 * scale, z - uz * 0.5 * scale + nz * 1.0 * scale, 0.45 * scale, 0.3 * scale, seed + 2, 0.35)
    rock(x - nx * 0.8 * scale, z - nz * 0.8 * scale, 0.28 * scale, 0.2 * scale, seed + 3, 0.4)
  }
  /** a pond's water level in this frame: its lowest bank, the bake's rule (city/package.ts waterLevels) */
  const level = (name: string): number => Math.min(...PONDS[name].map(([cx, cz]) => g(...L(cx, cz))))
  const levels: Record<string, number> = {}
  for (const name of Object.keys(PONDS)) levels[name] = level(name)
  const pondAt = (cx: number, cz: number): string => {
    let best = 'main', bd = Infinity
    for (const [name, ring] of Object.entries(PONDS)) {
      let sx = 0, sz = 0
      for (const [px, pz] of ring) { sx += px; sz += pz }
      const d = Math.hypot(sx / ring.length - cx, sz / ring.length - cz)
      if (d < bd) { bd = d; best = name }
    }
    return best
  }

  // ---- the cloud-pruned pines, and the little ones on Waterfall Hill: the library's `niwaki` (assetkit bushgen,
  // 2026-10-26: a crooked trunk, near-level limbs each ending in a flat cloud of needle cards; the builder's own —
  // struts with lump pads, 9,400 triangles for 21 — read as stacked green plates)
  for (const [cx, cz, hh, , seed] of [...PINES, ...DWARF_PINES]) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species: 'niwaki', h: hh, spin: (seed % 360) * (Math.PI / 180) })
  }
  // ---- the plant library's: the dwarf mugo pines and junipers, the massed azaleas, the irises, the ferns, the reeds
  for (const [cx, cz, species, hh] of DWARF) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species, h: hh, spin: h1(cx, cz) * Math.PI * 2 })
  }
  for (const [cx, cz, hh] of AZALEAS) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species: 'azalea', h: hh, spin: h1(cx + 1, cz) * Math.PI * 2 })
  }
  for (const [cx, cz, hh] of IRIS) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species: 'japanese_iris', h: hh, spin: h1(cx + 2, cz) * Math.PI * 2 })
  }
  for (const [cx, cz, species, hh] of FERNS) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species, h: hh, spin: h1(cx + 3, cz) * Math.PI * 2 })
  }
  for (const [cx, cz, species, hh] of REEDS) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species, h: hh, spin: h1(cz, cx) * Math.PI * 2 })
  }
  // ---- clipped azalea domes (tamamono) behind the waterline: the green hero mounds, modelled; the ones in flower are
  // the library's azalea instead (a flat-lit pink lump read as plastic however dark its colour, 2026-10-26)
  for (const [cx, cz, r, hh, c] of DOMES) {
    const [x, z] = L(cx, cz)
    if (c !== 'green') { out.plants.push({ x, z, species: 'azalea', h: Math.max(0.6, hh * 1.2), spin: h1(cx + 5, cz) * Math.PI * 2 }); continue }
    lump(out, x, g(x, z) - 0.12, z, r, hh, r * (0.85 + 0.25 * h1(cx, cz)), Math.round(cx * 7 + cz), CLIPPED, 0, 0.05, 8, 3, true, 0.2)
  }
  // ---- rocks at the waterline, and the rock groups
  for (const [cx, cz, r, hh, seed] of POND_ROCKS) rock(...L(cx, cz), r, hh, seed)
  for (const [cx, cz, bearing, scale] of ROCK_GROUPS) rockGroup(...L(cx, cz), bearing, scale, Math.round(cx + cz * 3) & 0xffff)

  // ---- the islands: a mossy mound rising from the water, stones round its waterline, a little pine on top
  for (const [cx, cz, r, kind] of ISLANDS) {
    const [x, z] = L(cx, cz)
    const lv = levels[pondAt(cx, cz)]
    const seed = Math.round(cx * 3 + cz) & 0xffff
    const tortoise = kind === 'tortoise'
    const rise = tortoise ? 0.4 : 0.55
    lump(out, x, lv - 0.25, z, r, rise + 0.25, r * (tortoise ? 0.7 : 0.9), seed, MOSS, 0, 0.08, 10, 3, true, 0.3)
    const n = tortoise ? 5 : 7
    for (let k = 0; k < n; k++) {
      const a = (k / n) * Math.PI * 2 + h1(seed, k) * 0.5
      const rr = r * (0.85 + 0.15 * h1(seed, k + 9))
      const rs = (tortoise ? 0.3 : 0.4) + 0.2 * h1(seed, k + 20)
      rock(x + Math.sin(a) * rr, z + Math.cos(a) * rr * (tortoise ? 0.7 : 0.9), rs, rs * 0.8, seed + k, 0.5, lv + 0.05)
    }
    if (tortoise) {
      // the tortoise's head: a stone standing off one end, its shell the mound
      standing(x + r * 1.05, z, 0.55, Math.PI / 2, seed + 50)
      out.plants.push({ x: x - r * 0.3, z: z + r * 0.2, species: 'niwaki', h: 1.7, spin: 3.5, dy: lv + rise - 0.05 - g(x - r * 0.3, z + r * 0.2) })
    } else {
      // (the stone pagoda on it is the owner's GLB; a pine leans out over the water beside where it stands)
      out.plants.push({ x: x + r * 0.45, z: z - r * 0.3, species: 'niwaki', h: 2.6, spin: 2.6, dy: lv + rise - 0.05 - g(x + r * 0.45, z - r * 0.3) })
      lump(out, x - r * 0.4, lv + rise - 0.1, z + r * 0.35, 0.7, 0.45, 0.6, seed + 70, CLIPPED, 0, 0.06, 7, 2, true, 0.3)
    }
  }
  // ---- lily pads on the water
  for (const [cx, cz, r] of PADS) {
    const [x, z] = L(cx, cz)
    const y = levels[pondAt(cx, cz)] + 0.04
    const a = h1(cx, cz) * Math.PI * 2, c = Math.cos(a) * r, s = Math.sin(a) * r
    const k = 0.9 + 0.2 * h1(cz, cx)
    out.quad([[x + c, y, z + s], [x - s * 0.9, y, z + c * 0.9], [x - c, y, z - s], [x + s * 0.9, y, z - c * 0.9]], [0, 1, 0], UV, shade(PAD, k), 0)
  }

  // ---- the Mt Fuji hedge: a broad clipped cone, a flat-topped cap; stones before it on the moss
  {
    const [x, z] = L(...FUJI)
    const y = g(x, z) - 0.35
    prism(out, x, z, y, y + 2.55, 2.9, 18, FUJI_GREEN, 0, 1.05)
    prism(out, x, z, y + 2.55, y + 2.95, 1.05, 18, shade(FUJI_GREEN, 1.12), 0, 0.6)
    for (const [cx, cz, r, hh, seed] of FUJI_ROCKS) rock(...L(cx, cz), r, hh, seed, 0.3)
  }
  // ---- the Dragon Hedges: clipped mounds along a line that winds, humped, the head end raised
  const dragon = (from: [number, number], to: [number, number], winds: number, seed: number): void => {
    const [ax, az] = L(...from), [bx, bz] = L(...to)
    const len = Math.hypot(bx - ax, bz - az), nx = -(bz - az) / len, nz = (bx - ax) / len
    const n = Math.round(len / 0.6)
    for (let i = 0; i <= n; i++) {
      const t = i / n
      const w = Math.sin(t * Math.PI * 2 * winds) * 0.8
      const x = ax + (bx - ax) * t + nx * w, z = az + (bz - az) * t + nz * w
      const hh = 0.85 + 0.45 * Math.abs(Math.sin(t * Math.PI * (winds + 1))) + (t > 0.88 ? (t - 0.88) * 7 : 0)
      lump(out, x, g(x, z) - 0.1, z, 0.64, hh, 0.64, seed + i * 17, DRAGON_GREEN, 0, 0.04, 8, 3, true, 0.2)
    }
  }
  dragon(DRAGON[0], DRAGON[1], 2, 0)
  dragon(DRAGON2[0], DRAGON2[1], 1, 500)
  // ---- bamboo: the library's culms (plantgen `bamboo`), a grove behind each hedge
  for (const [cx, cz, hh, seed] of BAMBOO) {
    const [x, z] = L(cx, cz)
    out.plants.push({ x, z, species: 'bamboo', h: hh, spin: (seed % 360) * (Math.PI / 180) })
  }

  // ---- a waterfall: ledges cut into the slope, each a still pool ending in a white drop, rocks along both banks and
  // at every lip, the last drop into the pond, foam where it meets the water
  const waterfall = (top: [number, number], foot: [number, number], pond: string, cuts: number[], seed: number): void => {
    const [tx, tz] = L(...top), [fx, fz] = L(...foot)
    const len = Math.hypot(fx - tx, fz - tz), ux = (fx - tx) / len, uz = (fz - tz) / len, nx = -uz, nz = ux
    const at = (t: number, side: number): [number, number] => [tx + ux * len * t + nx * side, tz + uz * len * t + nz * side]
    const W = 0.55
    // each ledge's water is level with the ground at its own downstream end, a little over it; the pond's is its own
    const level = cuts.map((t, k) => (k === cuts.length - 1 ? levels[pond] : g(...at(t, 0)) + 0.08))
    for (let k = 1; k < level.length; k++) level[k] = Math.min(level[k], level[k - 1] - 0.05)
    for (let k = 0; k < cuts.length - 1; k++) {
      const t0 = cuts[k], t1 = cuts[k + 1], y = level[k + 1]
      if (k === cuts.length - 2) {
        // the last reach: from the lip down to the water, a white fall into the pond
        const a = at(t0, -W * 0.8), b = at(t0, W * 0.8), c = at(t1, W * 0.9), d = at(t1, -W * 0.9)
        out.quad([[a[0], level[k], a[1]], [b[0], level[k], b[1]], [c[0], y, c[1]], [d[0], y, d[1]]], [ux * 0.5, 0.86, uz * 0.5], UV, FOAM, 0)
        continue
      }
      const p0 = at(t0, -W), p1 = at(t1, -W), p2 = at(t1, W), p3 = at(t0, W)
      out.quad([[p0[0], y, p0[1]], [p1[0], y, p1[1]], [p2[0], y, p2[1]], [p3[0], y, p3[1]]], [0, 1, 0], UV, WATER, 0)
      // the drop off this ledge's lip, down to the next
      const yb = level[k + 2]
      const a = at(t1, -W * 0.8), b = at(t1, W * 0.8)
      out.quad([[a[0], y, a[1]], [b[0], y, b[1]], [b[0], yb, b[1]], [a[0], yb, a[1]]], [ux, 0, uz], UV, FOAM, 0)
      for (const sd of [-1, 1]) {
        const [rx, rz] = at(t1, sd * (W + 0.35))
        lump(out, rx, y - 0.15, rz, 0.55, 0.5, 0.5, seed + k * 7 + (sd > 0 ? 3 : 0), ROCKS[(k + 1) % 4], ROCK, 0.36, 6, 3)
      }
    }
    // the banks: rocks the length of it, larger at the top
    const nb = Math.max(4, Math.round(len / 1.1))
    for (let i = 0; i <= nb; i++) {
      const t = i / nb
      for (const sd of [-1, 1]) {
        const [rx, rz] = at(t, sd * (W + 0.55 + 0.3 * h1(i, sd)))
        const r = 0.75 - 0.35 * t + 0.2 * h1(sd, i)
        rock(rx, rz, r, r * 0.8, seed + 400 + i * 2 + (sd > 0 ? 1 : 0), 0.3)
      }
    }
    // the spring: a heap of stones at the top, one standing over it; the foam at the foot
    for (let k = 0; k < 3; k++) {
      const [rx, rz] = at(-0.08, (k - 1) * 0.9)
      rock(rx, rz, 0.8, 0.75, seed + 450 + k, 0.25)
    }
    const [sx, sz] = at(-0.2, 0.3)
    standing(sx, sz, 1.5, Math.atan2(ux, uz), seed + 460)
    const [ex, ez] = at(1.0, 0)
    lump(out, ex + ux * 0.6, levels[pond] + 0.02, ez + uz * 0.6, 1.1, 0.1, 0.9, seed + 77, FOAM, 0, 0.1, 8, 2, true)
  }
  waterfall(FALL.top, FALL.foot, 'main', [0, 0.32, 0.62, 0.86, 1], 0)
  waterfall(FALL2.top, FALL2.foot, 'teahouse', [0, 0.45, 0.8, 1], 1000)

  // ---- the stream between the drum bridge pond and the Main Pond: a ribbon of water a little over the ground,
  // stepping down to the Main Pond, small stones along it
  {
    const [ax, az] = L(...STREAM[0]), [bx, bz] = L(...STREAM[1])
    const len = Math.hypot(bx - ax, bz - az), nx = -(bz - az) / len, nz = (bx - ax) / len
    const n = Math.max(2, Math.round(len / 0.8))
    let prev = Infinity
    const pts: { x: number; z: number; y: number }[] = []
    for (let i = 0; i <= n; i++) {
      const t = i / n, x = ax + (bx - ax) * t, z = az + (bz - az) * t
      const y = Math.min(prev, g(x, z) + 0.06)
      prev = y
      pts.push({ x, z, y })
    }
    const W = 0.7
    for (let i = 0; i < n; i++) {
      const a = pts[i], b = pts[i + 1]
      out.quad([[a.x - nx * W, a.y, a.z - nz * W], [b.x - nx * W, b.y, b.z - nz * W], [b.x + nx * W, b.y, b.z + nz * W], [a.x + nx * W, a.y, a.z + nz * W]], [0, 1, 0], UV, WATER, 0)
      for (const sd of [-1, 1]) if (h1(i, sd) < 0.6) rock(a.x + nx * sd * (W + 0.25), a.z + nz * sd * (W + 0.25), 0.3 + 0.2 * h1(sd, i), 0.25, 500 + i * 2 + (sd > 0 ? 1 : 0), 0.4)
    }
  }
}
