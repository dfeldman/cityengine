const DECK: Rgb = [0.46, 0.4, 0.33]
const FLOAT: Rgb = [0.78, 0.78, 0.76]

export function sausalitoHouseboatDocks(out: MeshBuilder): void {
  for (const line of DOCKS) {
    const p = line.map(([lat, lon]) => ({ x: (lon - ANCHOR.lon) * KX, z: (lat - ANCHOR.lat) * KZ }))
    for (let i = 1; i < p.length; i++) {
      const a = p[i - 1], b = p[i], L = Math.hypot(b.x - a.x, b.z - a.z)
      if (L < 0.3) continue
      const h = Math.atan2(b.x - a.x, b.z - a.z)
      const cx = (a.x + b.x) / 2, cz = (a.z + b.z) / 2
      // the white float under it and the planked deck on top (box: half-sizes, turned by its heading)
      turned(out, cx, -0.25, cz, 1.2, 0.3, L / 2 + 0.6, h, FLOAT)
      turned(out, cx, 0.08, cz, 1.1, 0.08, L / 2 + 0.55, h, DECK, surfaceTag('planks'))
    }
  }
}

/** a box turned about y so its local z runs along heading h */
function turned(out: MeshBuilder, cx: number, cy: number, cz: number, hx: number, hy: number, hz: number, h: number, c: Rgb, tag = FIXED): void {
  const s = Math.sin(h), co = Math.cos(h)
  const P = (dx: number, dy: number, dz: number): [number, number, number] => [cx + dx * co + dz * s, cy + dy, cz - dx * s + dz * co]
  const faces: [[number, number, number][], [number, number, number]][] = [
    [[P(-hx, hy, -hz), P(-hx, hy, hz), P(hx, hy, hz), P(hx, hy, -hz)], [0, 1, 0]],
    [[P(-hx, -hy, hz), P(hx, -hy, hz), P(hx, hy, hz), P(-hx, hy, hz)], [s, 0, co]],
    [[P(hx, -hy, -hz), P(-hx, -hy, -hz), P(-hx, hy, -hz), P(hx, hy, -hz)], [-s, 0, -co]],
    [[P(hx, -hy, hz), P(hx, -hy, -hz), P(hx, hy, -hz), P(hx, hy, hz)], [co, 0, -s]],
    [[P(-hx, -hy, -hz), P(-hx, -hy, hz), P(-hx, hy, hz), P(-hx, hy, -hz)], [-co, 0, s]],
  ]
  for (const [q, n] of faces) out.quad(q as [[number, number, number], [number, number, number], [number, number, number], [number, number, number]], n, [[0, 0], [1, 0], [1, 1], [0, 1]], c, tag)
}
