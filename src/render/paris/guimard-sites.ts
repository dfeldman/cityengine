/** Within `r` metres of a listed Guimard entrance? Points given in the city's local metres. */
export function guimardTest(toLocal: (lat: number, lon: number) => { x: number; z: number }, r = 20): (x: number, z: number) => boolean {
  const at = GUIMARD_SITES.map(([lat, lon]) => toLocal(lat, lon))
  return (x, z) => at.some((p) => Math.abs(p.x - x) < r && Math.abs(p.z - z) < r && Math.hypot(p.x - x, p.z - z) < r)
}
